"""Write eval reports: ``reports/<config>.json`` (all details) and ``.md`` (summary)."""

from __future__ import annotations

import json
from pathlib import Path


def pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def render_markdown(report: dict) -> str:
    s = report["summary"]
    k = report["k"]
    a = s["answerable"]
    cfg = report["config"]
    lines = [
        f"# Eval report: `{cfg['name']}`",
        "",
        f"{cfg['description']}",
        "",
        f"- Embedder: `{report['embedder']}`",
        f"- Generator: `{report['generator']}`",
        f"- Judge: `{report['judge']}`",
        f"- Questions: {s['n']} ({a['n']} answerable, {s['n'] - a['n']} unanswerable)",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Retrieval hit rate@{k} | {pct(a[f'hit_rate@{k}'])} |",
        f"| Retrieval recall@{k} | {pct(a[f'recall@{k}'])} |",
        f"| MRR | {a['mrr']:.3f} |",
        f"| Evidence@{k} (answer passage retrieved) | {pct(a[f'evidence@{k}'])} |",
        f"| Answer correctness | {pct(a['correctness'])} |",
        f"| Key-fact recall | {pct(a['key_fact_recall'])} |",
        f"| Token F1 | {pct(a['token_f1'])} |",
        f"| Refusal accuracy | {pct(s['refusal']['accuracy'])} |",
        f"| Unanswerable refused | {s['refusal']['unanswerable_refused']} |",
        f"| Answerable wrongly refused | {s['refusal']['answerable_refused']} |",
        f"| LLM cost | ${s['cost_usd']:.4f} |",
        "",
        "## By question type",
        "",
        f"| Type | n | hit@{k} | recall@{k} | MRR | evidence@{k} | correctness |",
        "|---|---|---|---|---|---|---|",
    ]
    for kind, b in s["by_type"].items():
        lines.append(
            f"| {kind} | {b['n']} | {pct(b[f'hit_rate@{k}'])} | {pct(b[f'recall@{k}'])} "
            f"| {b['mrr']:.3f} | {pct(b[f'evidence@{k}'])} | {pct(b['correctness'])} |"
        )
    lines += [
        "",
        "## Per question",
        "",
        f"| id | type | hit@{k} | RR | correctness | refusal ok | first retrieved |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in report["items"]:
        first = r["retrieved"][0] if r["retrieved"] else "-"
        if r["should_refuse"]:
            lines.append(
                f"| {r['id']} | {r['type']} | - | - | - | "
                f"{'yes' if r['refusal_correct'] else 'NO'} | {first} |"
            )
        else:
            lines.append(
                f"| {r['id']} | {r['type']} | {r[f'hit@{k}']:.0f} | {r['rr']:.2f} "
                f"| {r['correctness']:.2f} | {'yes' if r['refusal_correct'] else 'NO'} | {first} |"
            )
    return "\n".join(lines) + "\n"


def write_report(report: dict, reports_dir: Path) -> tuple[Path, Path]:
    reports_dir.mkdir(parents=True, exist_ok=True)
    name = report["config"]["name"]
    json_path = reports_dir / f"{name}.json"
    md_path = reports_dir / f"{name}.md"
    json_path.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    md_path.write_text(render_markdown(report), encoding="utf-8")
    return json_path, md_path


def _delta(value: float, base: float) -> str:
    diff = (value - base) * 100
    return "" if abs(diff) < 0.05 else f" ({diff:+.1f})"


def render_results(reports: list[dict]) -> str:
    """The comparison table committed as ``reports/RESULTS.md`` (generated by ``make eval-all``)."""
    base = next(r for r in reports if r["config"]["name"] == "baseline")
    k = base["k"]
    b = base["summary"]["answerable"]
    first = reports[0]
    lines = [
        "# Results",
        "",
        "Generated by `make eval-all` from `evals/golden.jsonl` "
        f"({first['summary']['n']} questions: {b['n']} answerable, "
        f"{first['summary']['n'] - b['n']} unanswerable). Do not edit by hand.",
        "",
        f"- **Embedder:** `{first['embedder']}`",
        f"- **Generator:** `{first['generator']}`",
        f"- **Judge (correctness):** `{first['judge']}`",
        "",
        "Numbers in parentheses are percentage-point changes vs. `baseline`.",
        "",
        f"| Config | What changes | Hit@{k} | MRR | Evidence@{k} | Multi-hop recall@{k} "
        "| Correctness | Token F1 | Refusal acc. |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in reports:
        a = r["summary"]["answerable"]
        mh = r["summary"]["by_type"].get("multi_hop", {}).get(f"recall@{k}", 0.0)
        mh_base = base["summary"]["by_type"].get("multi_hop", {}).get(f"recall@{k}", 0.0)
        refusal = r["summary"]["refusal"]["accuracy"]
        refusal_base = base["summary"]["refusal"]["accuracy"]
        lines.append(
            f"| `{r['config']['name']}` | {r['config']['description']} "
            f"| {pct(a[f'hit_rate@{k}'])}{_delta(a[f'hit_rate@{k}'], b[f'hit_rate@{k}'])} "
            f"| {a['mrr']:.3f} "
            f"| {pct(a[f'evidence@{k}'])}{_delta(a[f'evidence@{k}'], b[f'evidence@{k}'])} "
            f"| {pct(mh)}{_delta(mh, mh_base)} "
            f"| {pct(a['correctness'])}{_delta(a['correctness'], b['correctness'])} "
            f"| {pct(a['token_f1'])}{_delta(a['token_f1'], b['token_f1'])} "
            f"| {pct(refusal)}{_delta(refusal, refusal_base)} |"
        )
    if all(r["summary"]["answerable"][f"hit_rate@{k}"] == 1.0 for r in reports):
        lines += [
            "",
            f"Hit@{k} is 100% for every config: on this small corpus the right *page* is always "
            f"in the top {k}, so file-level hit rate cannot separate the configs. MRR, "
            "evidence@k (did the answer-bearing passage reach the prompt?) and answer "
            "correctness are the informative columns.",
        ]
    return "\n".join(lines) + "\n"
